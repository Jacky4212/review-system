def make_doc():
    doc = Document()
    style = doc.styles['Normal']
    font = style.font
    font.name = 'Microsoft YaHei'
    font.size = Pt(11)
    style.element.rPr.rFonts.set(qn('w:eastAsia'), 'Microsoft YaHei')
    return doc

def add_title(doc, text, level=0):
    h = doc.add_heading('', level=level)
    h.add_run(text).font.color.rgb = RGBColor(0x1a, 0x3a, 0x5c)

def add_q(doc, q, a, src=''):
    p = doc.add_paragraph()
    r = p.add_run('【原题】'); r.bold = True; r.font.color.rgb = RGBColor(0x2d, 0x7f, 0xc1)
    p.add_run(' ' + q)
    p2 = doc.add_paragraph()
    r2 = p2.add_run('【答案】'); r2.bold = True; r2.font.color.rgb = RGBColor(0xc0, 0x39, 0x2b)
    p2.add_run(' ' + a)
    if src:
        p3 = doc.add_paragraph()
        r3 = p3.add_run('【来源】'); r3.bold = True; r3.font.color.rgb = RGBColor(0x27, 0xae, 0x60)
        p3.add_run(' ' + src)
    doc.add_paragraph('')

def save(doc, name):
    path = os.path.join(OUTPUT_DIR, name)
    doc.save(path)
    print("已保存: " + path)

